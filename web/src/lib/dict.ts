const DICTS: Record<Locale, Dict> = { nl, fr, en };
export const getDict = (locale: Locale): Dict => DICTS[locale];

/** "18 oktober 2026" of, als de shops een andere datum hebben, "… (bol) en … (Amazon)". */
export function shopDates(locale: Locale, bol: string, amazon: string): string {
  if (bol === amazon) return bol;
  const and = { nl: 'en', fr: 'et', en: 'and' }[locale];
  return `${bol} (bol) ${and} ${amazon} (Amazon)`;
}
